export class LocalizationManager {
  private currentLang: LanguageCode = 'en';
  private listeners = new Set<(lang: LanguageCode) => void>();

  setLanguage(lang: LanguageCode): void {
    if (!DICTIONARIES[lang]) return;
    this.currentLang = lang;
    for (const cb of this.listeners) cb(lang);
  }

  getLanguage(): LanguageCode {
    return this.currentLang;
  }

  onChange(cb: (lang: LanguageCode) => void): () => void {
    this.listeners.add(cb);
    return () => this.listeners.delete(cb);
  }

  t(key: string, params?: Record<string, string | number>): string {
    const dict = DICTIONARIES[this.currentLang] ?? DICTIONARIES.en;
    let text = dict[key] ?? DICTIONARIES.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return text;
  }
}

export const i18n = new LocalizationManager();
